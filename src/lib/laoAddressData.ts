export function getDistrictsByProvince(provinceName: string): string[] {
  const prov = LAO_PROVINCES.find((p) => p.name === provinceName);
  return prov ? prov.districts : [];
}

export function formatLaoAddress(parts: {
  village?: string;
  district?: string;
  province?: string;
}): string {
  const { village, district, province } = parts;
  const segments: string[] = [];

  if (village && village.trim()) {
    const v = village.trim();
    segments.push(v.startsWith("ບ້ານ") ? v : `ບ້ານ ${v}`);
  }

  if (district && district.trim()) {
    const d = district.trim();
    segments.push(d.startsWith("ເມືອງ") || d.startsWith("ນະຄອນ") ? d : `ເມືອງ ${d}`);
  }

  if (province && province.trim()) {
    const p = province.trim();
    segments.push(p);
  }

  return segments.join(", ");
}

export function parseLaoAddress(addressStr: string): {
  village: string;
  district: string;
  province: string;
} {
  if (!addressStr) return { village: "", district: "", province: "" };

  let foundProvince = "";
  for (const p of LAO_PROVINCES) {
    if (addressStr.includes(p.name)) {
      foundProvince = p.name;
      break;
    }
  }

  let foundDistrict = "";
  if (foundProvince) {
    const districts = getDistrictsByProvince(foundProvince);
    for (const d of districts) {
      if (addressStr.includes(d)) {
        foundDistrict = d;
        break;
      }
    }
  } else {
    for (const p of LAO_PROVINCES) {
      for (const d of p.districts) {
        if (addressStr.includes(d)) {
          foundDistrict = d;
          foundProvince = p.name;
          break;
        }
      }
      if (foundDistrict) break;
    }
  }

  let village = "";
  const matchVillage = addressStr.match(/ບ້ານ\s*([^,]+)/);
  if (matchVillage) {
    village = matchVillage[1].trim();
  }

  return {
    province: foundProvince,
    district: foundDistrict,
    village,
  };
}
